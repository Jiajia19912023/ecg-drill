'use client';
// ===== 設定(言語・画面の色・記録の書き出し/読み込み/リセット・このアプリについて) =====
import { useApp } from '../AppCtx';
import { NavBar, PlainTop } from '../ui';

export function Settings() {
  const { L, S, store, act, lang } = useApp();
  const theme = store.theme === 'dark' ? 'dark' : 'light';
  return (
    <>
      <PlainTop title={L('設定', 'Settings')} />
      <main className="wrap grow">
        <h2>{L('表示', 'Display')}</h2>
        <div className="card col" style={{ gap: 8 }}>
          <span className="sub">{L('言語', 'Language')}</span>
          <div className="seg" style={{ gridTemplateColumns: 'repeat(2,1fr)' }}>
            <button type="button" className={lang === 'ja' ? 'on' : ''} aria-pressed={lang === 'ja'} onClick={() => act.setLang('ja')} lang="ja">日本語</button>
            <button type="button" className={lang === 'en' ? 'on' : ''} aria-pressed={lang === 'en'} onClick={() => act.setLang('en')} lang="en">English</button>
          </div>
          <span className="sub" style={{ marginTop: 6 }}>{L('画面の色', 'Theme')}</span>
          <div className="seg" style={{ gridTemplateColumns: 'repeat(2,1fr)' }}>
            {(['light', 'dark'] as const).map((th) => (
              <button key={th} type="button" className={theme === th ? 'on' : ''} aria-pressed={theme === th} onClick={() => act.theme(th)}>{th === 'light' ? L('ライト', 'Light') : L('ダーク', 'Dark')}</button>
            ))}
          </div>
          <span className="sub">{L('心電図の方眼紙は、ダークでも実際の記録用紙と同じ色で表示します。', 'ECG paper keeps its real colors even in dark mode.')}</span>
        </div>

        <h2>{L('記録のリセット', 'Reset records')}</h2>
        <div className="card col" style={{ gap: 10 }}>
          {S.confirmReset ? (
            <>
              <p style={{ margin: 0, fontWeight: 700, color: '#B91C1C' }}>{L('すべての記録を消します。よろしいですか?', 'This deletes all of your records. Are you sure?')}</p>
              <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 10 }}>
                <button type="button" className="btn sec" onClick={act.cancelReset}>{L('やめる', 'Cancel')}</button>
                <button type="button" className="btn danger" onClick={act.doReset}>{L('消す', 'Delete')}</button>
              </div>
            </>
          ) : <button type="button" className="btn sec" onClick={act.askReset}>{L('記録をすべて消す', 'Delete all records')}</button>}
        </div>

        <h2>{L('このアプリについて', 'About')}</h2>
        <div className="card" style={{ fontSize: 13, lineHeight: 1.7 }}>
          <p style={{ marginTop: 0 }}><b>ECG DRILL</b></p>
          <p>{L('本アプリは教育目的です。診断や治療の判断には使わないでください。実際の臨床では、施設の手順と医師の判断に従ってください。', 'This app is for education only. Do not use it for diagnosis or treatment decisions. In clinical practice, follow your facility’s protocols and the physician’s judgment.')}</p>
          <p>{L('心電図の波形は、学習用にプログラムで描いた模式的なサンプルです。今後、PTB-XL(Wagner P, et al. PhysioNet, CC BY 4.0)の実波形に置き換える予定です。', 'The ECG waveforms are schematic samples generated by the app for learning. They will be replaced with real tracings from PTB-XL (Wagner P, et al. PhysioNet, CC BY 4.0).')}</p>
          <p>{L('患者さんの情報を入力する機能はありません。記録はこの端末のブラウザにだけ保存されます(ログインなし・サーバーには送りません)。ブラウザのデータを消すと、記録も消えます。', 'There is no way to enter patient information. Records are stored only in this browser on this device (no login, nothing sent to a server). Clearing browser data deletes them.')}</p>
          <p style={{ marginBottom: 0 }}>{L('主な根拠:', 'Main references: ')}AHA/ACCF/HRS Recommendations for the Standardization and Interpretation of the ECG, Part I–VI (2007, 2009) / Fourth Universal Definition of Myocardial Infarction (2018)</p>
        </div>
      </main>
      <NavBar on="settings" />
    </>
  );
}
